#!/usr/bin/env node
/**
 * build-site-index.js — write the standing facts the chatbot reads.
 *
 *   node scripts/build-site-index.js           # write functions/api/lib/site-index.js
 *   node scripts/build-site-index.js --check   # exit 1 if the committed file is stale
 *
 * Two things the chatbot cannot get from retrieval, so they go into its prompt
 * directly, generated from the same files the site renders:
 *
 *   POSTS     every blog post, newest first. Similarity search cannot rank by
 *             date: asked for the latest post it named an August one weeks
 *             after four newer ones went up.
 *   ROLES,    work and projects. These were typed into the prompt by hand and
 *   PROJECTS  still named a job that ended in 2025 and projects the site had
 *             dropped.
 *
 * Runs as `prebuild`, and a test fails if the committed copy has drifted.
 */
const fs   = require('fs');
const path = require('path');
const { listBlogs, listRoles, listProjects, siteHeadline } = require('./lib/sources');

// A JavaScript module rather than JSON: a bare JSON import works in the
// Functions bundler but not in plain Node, and both need to read it.
const OUT = path.join(__dirname, '..', 'functions', 'api', 'lib', 'site-index.js');
const out = (name, value) => `export const ${name} = ${JSON.stringify(value, null, 2)};\n`;
const body = '// Generated by scripts/build-site-index.js from src/data and src/i18n. Do not edit.\n\n' +
  out('HEADLINE', siteHeadline()) + '\n' +
  out('ROLES', listRoles()) + '\n' +
  out('PROJECTS', listProjects()) + '\n' +
  out('POSTS', listBlogs());

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf-8') : '';
  if (current !== body) {
    console.error('site-index.js is stale. Run: node scripts/build-site-index.js');
    process.exit(1);
  }
  console.log('site-index.js is up to date');
} else {
  fs.writeFileSync(OUT, body);
  console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
}
