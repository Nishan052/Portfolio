#!/usr/bin/env node
/**
 * build-blog-index.js — write the blog list the chatbot reads.
 *
 *   node scripts/build-blog-index.js           # write functions/api/lib/blog-index.js
 *   node scripts/build-blog-index.js --check   # exit 1 if the committed file is stale
 *
 * The chatbot finds context by similarity, and "which post is the latest" is not
 * a similarity question: it returned an August post weeks after four newer ones
 * were published. So the list of posts and their dates goes into the system
 * prompt directly, generated from the same files the blog page reads.
 *
 * Runs as `prebuild`, and a test fails if the committed copy has drifted.
 */
const fs   = require('fs');
const path = require('path');
const { listBlogs } = require('./lib/sources');

// A JavaScript module rather than JSON: a bare JSON import works in the
// Functions bundler but not in plain Node, and both need to read it.
const OUT  = path.join(__dirname, '..', 'functions', 'api', 'lib', 'blog-index.js');
const LIST = listBlogs();
const body = '// Generated by scripts/build-blog-index.js. Do not edit.\n' +
             `export default ${JSON.stringify(LIST, null, 2)};\n`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf-8') : '';
  if (current !== body) {
    console.error('blog-index.js is stale. Run: node scripts/build-blog-index.js');
    process.exit(1);
  }
  console.log('blog-index.js is up to date');
} else {
  fs.writeFileSync(OUT, body);
  console.log(`wrote ${path.relative(process.cwd(), OUT)} (${LIST.length} posts)`);
}
