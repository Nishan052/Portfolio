#!/usr/bin/env node
/**
 * build-routing-files.js — tell crawlers and the host which URLs are real.
 *
 *   node scripts/build-routing-files.js           # write public/sitemap.xml and public/_redirects
 *   node scripts/build-routing-files.js --check   # exit 1 if the committed files are stale
 *
 * The site is a single-page app, and Cloudflare Pages answers every unknown path
 * with index.html and a 200 when a project has no 404.html. Scanners asking for
 * /xxx.php or /__debugger__ therefore got a success, and a crawler asking for
 * /sitemap.xml got the home page instead of a sitemap.
 *
 *   sitemap.xml   the pages worth indexing, from the same blog files the site renders
 *   _redirects    one rewrite per real route, so the app is served for those and
 *                 public/404.html (a real 404) is served for everything else
 *
 * The rewrite target is "/" and not "/index.html". Cloudflare Pages redirects any
 * request for /index.html or a .html file to its pretty URL, so a rule pointing at
 * index.html sends every real route to the home page. Tested with wrangler pages dev.
 *
 * A new blog post is a new route, so both files change with it. Runs as part of
 * `prebuild`, and a test fails if the committed copies have drifted.
 */
const fs   = require('fs');
const path = require('path');
const { listBlogs } = require('./lib/sources');

const ROOT   = path.join(__dirname, '..');
const PUBLIC = path.join(ROOT, 'public');

// Read the address from the site config so there is one place to change it.
const BASE_URL = fs.readFileSync(path.join(ROOT, 'src', 'config', 'site.js'), 'utf-8')
  .match(/baseUrl:\s*['"`](.+?)['"`]/)[1];

// The routes App.js declares, other than the blog posts. /deck redirects to / and
// /classic is the older home page, so neither belongs in the sitemap.
const APP_ROUTES = ['/deck', '/classic', '/blogs'];

const posts = listBlogs();

const sitemap = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  `  <url><loc>${BASE_URL}/</loc></url>`,
  `  <url><loc>${BASE_URL}/blogs</loc><lastmod>${posts[0] ? posts[0].date : ''}</lastmod></url>`,
  ...posts.map(p => `  <url><loc>${BASE_URL}/blogs/${p.slug}</loc><lastmod>${p.date}</lastmod></url>`),
  '</urlset>',
  '',
].join('\n').replace('<lastmod></lastmod>', '');

const redirects = [
  '# Generated by scripts/build-routing-files.js. Do not edit.',
  '# Each real route is rewritten to the app. Anything else gets public/404.html.',
  ...[...APP_ROUTES, ...posts.map(p => `/blogs/${p.slug}`)]
    .flatMap(route => [route, `${route}/`])   // links with a trailing slash worked before, so keep them
    .map(route => `${route} / 200`),
  '',
].join('\n');

const FILES = { 'sitemap.xml': sitemap, '_redirects': redirects };

if (process.argv.includes('--check')) {
  const stale = Object.entries(FILES).filter(([name, body]) => {
    const file = path.join(PUBLIC, name);
    return !fs.existsSync(file) || fs.readFileSync(file, 'utf-8') !== body;
  }).map(([name]) => name);
  if (stale.length) {
    console.error(`${stale.join(' and ')} stale. Run: node scripts/build-routing-files.js`);
    process.exit(1);
  }
  console.log('sitemap.xml and _redirects are up to date');
} else {
  for (const [name, body] of Object.entries(FILES)) {
    fs.writeFileSync(path.join(PUBLIC, name), body);
    console.log(`wrote ${path.relative(process.cwd(), path.join(PUBLIC, name))}`);
  }
}
